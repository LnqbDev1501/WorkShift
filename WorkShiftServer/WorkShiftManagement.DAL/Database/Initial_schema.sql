    face_quality_score numeric(5,4) CHECK (face_quality_score BETWEEN 0 AND 1),
    liveness_score numeric(5,4) NOT NULL CHECK (liveness_score BETWEEN 0 AND 1),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'REVOKED')),
    registered_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_initial_face_image CHECK (registration_type <> 'INITIAL' OR registration_image_url IS NOT NULL),
