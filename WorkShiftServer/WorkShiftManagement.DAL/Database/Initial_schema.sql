CREATE TABLE public.contract_change_requests (
    change_request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    contract_id integer NOT NULL UNIQUE
        REFERENCES public.employment_contracts(contract_id) ON DELETE RESTRICT,

    requested_by uuid NOT NULL
        REFERENCES public.users(user_id) ON DELETE RESTRICT,

    request_type varchar(30) NOT NULL
        CHECK (request_type IN ('ACCEPTANCE', 'CHANGE_REQUEST')),

    staff_comment text NULL,

    status varchar(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED')),

    submitted_at timestamptz NULL,

    reviewed_by uuid NULL
        REFERENCES public.users(user_id) ON DELETE RESTRICT,

    reviewed_at timestamptz NULL,

    review_comment text NULL,

    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

	CONSTRAINT ck_contract_change_request_submitted
    CHECK (
        status <> 'SUBMITTED'
        OR submitted_at IS NOT NULL
    ),

	CONSTRAINT ck_contract_change_request_reviewed
    CHECK (
        status NOT IN ('APPROVED', 'REJECTED')
        OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    ),

	CONSTRAINT ck_acceptance_not_draft
    CHECK (
        request_type <> 'ACCEPTANCE'
        OR status <> 'DRAFT'
    )


);

