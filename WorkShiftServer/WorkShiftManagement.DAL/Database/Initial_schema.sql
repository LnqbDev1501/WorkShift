-- ===== 1. Reference and identity tables =====
CREATE TABLE public.roles (
    role_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name varchar(50) NOT NULL UNIQUE,
    description varchar(500),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.regions (
    region_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_code varchar(20) NOT NULL UNIQUE,
    region_name varchar(150) NOT NULL UNIQUE,
    description varchar(500),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.employee_types (
    employee_type_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name varchar(100) NOT NULL UNIQUE,
    description varchar(500),
    max_shifts_per_week integer CHECK (max_shifts_per_week > 0),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.branches (
    branch_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code varchar(30) NOT NULL UNIQUE,
    branch_name varchar(150) NOT NULL,
    region_id integer NOT NULL REFERENCES public.regions(region_id) ON DELETE RESTRICT,
    address varchar(500) NOT NULL,
    latitude numeric(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude numeric(10,6) CHECK (longitude BETWEEN -180 AND 180),
    phone varchar(20),
    email varchar(254),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'CLOSED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_branch_name UNIQUE (branch_name)
);

CREATE TABLE public.users (
    user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE RESTRICT,
    role_id integer NOT NULL REFERENCES public.roles(role_id) ON DELETE RESTRICT,
    branch_id integer REFERENCES public.branches(branch_id) ON DELETE RESTRICT,
    employee_type_id integer REFERENCES public.employee_types(employee_type_id) ON DELETE RESTRICT,
    full_name varchar(150) NOT NULL,
    gender varchar(10) NOT NULL CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    date_of_birth date NOT NULL,
    avatar_url varchar(500) NOT NULL DEFAULT,
    address varchar(500) NOT NULL,
    identity_no varchar(30) NOT NULL UNIQUE,
    email varchar(254) NOT NULL UNIQUE,
    phone varchar(20) NOT NULL UNIQUE,
    status varchar(30) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACTIVE', 'INACTIVE')),
    previous_status varchar(30),
    deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.shift_templates (
    shift_template_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_name varchar(150) NOT NULL UNIQUE,
    start_time time NOT NULL,
    end_time time NOT NULL,
    break_minutes integer NOT NULL DEFAULT 0 CHECK (break_minutes >= 0),
    description varchar(500),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- ===== 2. Scheduling and assignments =====

CREATE TABLE public.work_schedule_weeks (
    schedule_week_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES public.branches(branch_id) ON DELETE RESTRICT,
    week_start_date date NOT NULL,
    week_end_date date NOT NULL,
    registration_deadline timestamptz NOT NULL,
    status varchar(30) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'OPEN_REGISTRATION', 'REGISTRATION_CLOSED', 'COMPLETED', 'CANCELLED')),
    created_by uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    opened_at timestamptz,
    registration_closed_at timestamptz,
    cancelled_by uuid REFERENCES public.users(user_id) ON DELETE RESTRICT,
    cancelled_at timestamptz,
    cancel_reason varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_schedule_week_monday CHECK (extract(isodow FROM week_start_date) = 1),
    CONSTRAINT ck_schedule_week_range CHECK (week_end_date = week_start_date + 6),
    CONSTRAINT ck_schedule_week_cancelled CHECK (
        (status <> 'CANCELLED') OR (cancelled_by IS NOT NULL AND cancelled_at IS NOT NULL)
    ),
    CONSTRAINT uq_schedule_week_branch_start UNIQUE (branch_id, week_start_date)
);

CREATE TABLE public.work_shifts (
    shift_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_week_id integer NOT NULL REFERENCES public.work_schedule_weeks(schedule_week_id) ON DELETE RESTRICT,
    shift_template_id integer NOT NULL REFERENCES public.shift_templates(shift_template_id) ON DELETE RESTRICT,
    shift_name_snapshot varchar(150) NOT NULL,
    scheduled_start_at timestamptz NOT NULL,
    scheduled_end_at timestamptz NOT NULL,
    break_minutes_snapshot integer NOT NULL DEFAULT 0 CHECK (break_minutes_snapshot >= 0),
    required_employees integer NOT NULL CHECK (required_employees > 0),
    note varchar(500),
    created_by uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    status varchar(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SCHEDULED', 'COMPLETED', 'CANCELLED')),
    cancelled_by uuid REFERENCES public.users(user_id) ON DELETE RESTRICT,
    cancelled_at timestamptz,
    cancel_reason varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_work_shift_range CHECK (scheduled_end_at > scheduled_start_at),
    CONSTRAINT ck_work_shift_cancelled CHECK (
        status <> 'CANCELLED' OR (cancelled_by IS NOT NULL AND cancelled_at IS NOT NULL)
    )
);

CREATE TABLE public.shift_assignments (
    assignment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id integer NOT NULL REFERENCES public.work_shifts(shift_id) ON DELETE RESTRICT,
    user_id uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    assignment_source varchar(30) NOT NULL
        CHECK (assignment_source IN ('SELF_REGISTRATION', 'MANAGER_ASSIGNMENT', 'SHIFT_SWAP')),
    assigned_by uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    assigned_at timestamptz NOT NULL DEFAULT now(),
    status varchar(20) NOT NULL DEFAULT 'ASSIGNED'
        CHECK (status IN ('ASSIGNED', 'COMPLETED', 'CANCELLED')),
    cancelled_by uuid REFERENCES public.users(user_id) ON DELETE RESTRICT,
    cancelled_at timestamptz,
    cancel_reason varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_shift_assignment UNIQUE (shift_id, user_id),
    CONSTRAINT ck_assignment_cancelled CHECK (
        status <> 'CANCELLED' OR (cancelled_by IS NOT NULL AND cancelled_at IS NOT NULL)
    )
);

CREATE TABLE public.shift_swap_requests (
    swap_request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    target_user_id uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    source_assignment_id integer NOT NULL REFERENCES public.shift_assignments(assignment_id) ON DELETE RESTRICT,
    target_assignment_id integer NOT NULL REFERENCES public.shift_assignments(assignment_id) ON DELETE RESTRICT,
    reason varchar(500),
    responded_by uuid REFERENCES public.users(user_id) ON DELETE RESTRICT,
    responded_at timestamptz,
    response_note varchar(500),
    status varchar(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_swap_different_users CHECK (requester_id <> target_user_id),
    CONSTRAINT ck_swap_different_assignments CHECK (source_assignment_id <> target_assignment_id)
);

CREATE TABLE public.checklists (
    checklist_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id integer NOT NULL REFERENCES public.work_shifts(shift_id) ON DELETE RESTRICT,
    checklist_name varchar(150) NOT NULL,
    description varchar(500),
    created_by uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE public.checklist_items (
    checklist_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checklist_id integer NOT NULL REFERENCES public.checklists(checklist_id) ON DELETE RESTRICT,
    item_name varchar(255) NOT NULL,
    is_required boolean NOT NULL DEFAULT true,
    display_order integer NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_checklist_item_order UNIQUE (checklist_id, display_order)
);

CREATE TABLE public.checklist_results (
    result_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checklist_item_id integer NOT NULL REFERENCES public.checklist_items(checklist_item_id) ON DELETE RESTRICT,
    user_id uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    is_completed boolean NOT NULL DEFAULT false,
    photo_url varchar(500),
    note varchar(500),
    completed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    is_deleted boolean NOT NULL DEFAULT false,
    CONSTRAINT uq_checklist_result_user_item UNIQUE (checklist_item_id, user_id)
);

-- ===== 3. Attendance rules, face verification and attendance =====
CREATE TABLE public.attendance_rules (
    attendance_rule_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES public.branches(branch_id) ON DELETE RESTRICT,
    rule_name varchar(150) NOT NULL,
    description text,
    check_in_before_minutes integer NOT NULL DEFAULT 30 CHECK (check_in_before_minutes >= 0),
    check_in_grace_minutes integer NOT NULL DEFAULT 0 CHECK (check_in_grace_minutes >= 0),
    check_out_grace_minutes integer NOT NULL DEFAULT 0 CHECK (check_out_grace_minutes >= 0),
    check_out_after_minutes integer NOT NULL DEFAULT 30 CHECK (check_out_after_minutes >= 0),
    require_gps boolean NOT NULL DEFAULT true,
    max_attendance_distance_meters integer CHECK (max_attendance_distance_meters > 0),
    require_face_verification boolean NOT NULL DEFAULT true,
    effective_from date,
    effective_to date,
    status varchar(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SCHEDULED', 'ACTIVE', 'INACTIVE', 'CANCELLED')),
    created_by uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    published_by uuid REFERENCES public.users(user_id) ON DELETE RESTRICT,
    published_at timestamptz,
    cancelled_by uuid REFERENCES public.users(user_id) ON DELETE RESTRICT,
    cancelled_at timestamptz,
    cancellation_reason text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_attendance_rule_dates CHECK (effective_to IS NULL OR effective_from IS NULL OR effective_to >= effective_from),
    CONSTRAINT ck_attendance_rule_effective CHECK (
        status NOT IN ('SCHEDULED', 'ACTIVE', 'INACTIVE') OR effective_from IS NOT NULL
    )
);

-- ===== Face verification =====
CREATE TABLE public.face_verification_sessions (
    session_id uuid PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    action_type varchar(30) NOT NULL
        CHECK (action_type IN ('INITIAL_REGISTRATION', 'REREGISTRATION', 'CHECK_IN', 'CHECK_OUT')),
