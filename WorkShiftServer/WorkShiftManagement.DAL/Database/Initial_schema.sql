    face_match_score numeric(5,4) CHECK (face_match_score BETWEEN 0 AND 1),
    challenge_sequence jsonb NOT NULL,
    nonce_hash varchar(255) NOT NULL UNIQUE,
    liveness_verified boolean NOT NULL DEFAULT false,
    liveness_score numeric(5,4) CHECK (liveness_score BETWEEN 0 AND 1),
    expires_at timestamptz NOT NULL,
    used_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_face_session_expiry CHECK (expires_at > created_at)
);

CREATE TABLE public.face_profiles (
    face_profile_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
